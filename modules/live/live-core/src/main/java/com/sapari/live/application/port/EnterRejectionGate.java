package com.sapari.live.application.port;

/**
 * 입장 거부가 <b>어느 관문</b>에서 났는가 — 대응이 반대라서 가른다.
 *
 * <p>{@link #SHARD} 는 <b>한 계정</b>이 자기 몫을 넘긴 것이다(그 계정을 찾는다).
 * {@link #GLOBAL} 은 <b>집계가 천장에 닿은</b> 것이다(한도·용량을 올린다). 둘이 같은 지표로
 * 합쳐지면 당직자가 그 판정을 못 하고, 그 판정이 바로 집단 태그를 넣은 이유였다.
 *
 * <p>⚠️ 샤드 몫의 합이 전역을 넘도록 올려 둔 뒤로는 <b>분산 과부하에서 거부의 다수가
 * {@code GLOBAL}</b> 이다. 그 전에는 회원 거부가 거의 전부 샤드 쪽이라 이 모호성이 작았다.
 */
public enum EnterRejectionGate {

    /** 계정 단위 샤드 버킷. 회원 경로에만 있다. */
    SHARD,

    /** 집단 전역 버킷. 게스트 거부는 항상 이쪽이다 — 게스트에는 샤드가 없다. */
    GLOBAL
}
