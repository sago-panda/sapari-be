package com.sapari.live.application.port;

/**
 * 룸 토큰이 <b>서명을 치고 나왔는가, 캐시에서 나왔는가</b>.
 *
 * <p>이 축이 없으면 캐시가 <b>도는 것과 헛도는 것</b>을 구분할 수 없다. 둘은 응답도 처리량도 같고
 * 차이가 CPU 에만 나타난다 — 적중률이 0 으로 떨어져도(설정이 작거나 수요가 전부 1회성이거나) 아무
 * 신호가 안 나고, 그 상태는 "캐시를 넣었다" 는 문장만 남기고 비용은 그대로인 모양이다.
 *
 * <p>대응이 갈린다. {@link #SIGNED} 비율이 높으면 <b>적중할 수 없는 수요</b>(1회성 입장)이거나
 * 슬롯이 작아 서로 밀어내는 것이고, 전자는 캐시를 키워도 안 낫는다. {@link #CACHED} 가 지배하면
 * 이 경로의 서명 비용이 실제로 빠진 것이다.
 *
 * <p>게스트는 이 수에 <b>등장하지 않는다</b> — 캐시를 읽지도 쓰지도 않으므로({@code
 * CachingRoomTokenIssuer} javadoc) 분모가 회원 입장뿐이다. 게스트를 섞으면 적중률이 구조적으로
 * 절반 아래로 눌려 "작게 잡았다" 와 구분이 안 된다.
 */
public enum RoomTokenSignatureSource {
    /** 개인키 서명을 실제로 쳤다 — 실측 688µs(RSA-2048, aarch64). */
    SIGNED,
    /** 같은 claim 으로 이미 발급한 토큰을 그대로 돌려줬다. */
    CACHED
}
