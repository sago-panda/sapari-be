package com.sapari.chat.domain.exception;

/**
 * 정본에 <b>이미</b> 규칙을 어기는 사전 항목이 있어 지금 상태로는 발행할 수 없다.
 *
 * <p><b>왜 이 예외가 필요한가.</b> 교체 지점의 게이트는 사전 <b>전체</b>에 규칙을 적용하고,
 * 떨어지면 그 Pod 은 교체를 포기한다. 그러면 정본에 어기는 행이 하나 있을 때 이런 조합이 생긴다:
 * 운영자가 멀쩡한 단어를 더하고 → 쓰기가 통과해 성공이 나가고 → 모든 Pod 이 스냅샷을 읽다가
 * 그 <b>옛 행</b>에 걸려 교체를 거부한다. 운영자는 성공을 받고 목록에서 자기 단어를 보는데
 * 어느 Pod 도 그것을 집행하지 않고, 그 뒤의 모든 변경도 같다 — <b>전파가 동결된다.</b>
 * 신호는 Pod 로그뿐이다.
 *
 * <p>그래서 쓰기 경로가 결과 사전 <b>전체</b>를 검사하고, 변경 전 집합이 이미 어기고 있으면
 * 이것을 던진다. 그 상태가 쓰기 시점에 드러나고, 고치는 길(그 항목 제거)이 같은 API 안에 있다.
 *
 * <p><b>이 상태에 닿는 길 둘.</b> 정본을 직접 고친 쓰기 — 그것이 교체 지점에 게이트를 둔 이유다 —
 * 와 <b>규칙을 나중에 조이는 것</b>이다. 두 번째가 더 중요하다: K 예산을 64 에서 16 으로 내린
 * 변경이 정확히 그 일이었고, 그때는 테이블이 비어 있어 피해가 없었다. 채워진 테이블에 같은 일을
 * 하면 범위 밖 행 하나가 전파를 멈춘다.
 *
 * <p>409 인 이유: 요청자 잘못이 아니고(보낸 항목은 멀쩡할 수 있다) 서버가 고장난 것도 아니다 —
 * 지금 상태로는 완료할 수 없고, 고치면 된다.
 *
 * <p>제거 요청은 이것을 던지지 않는 경우가 있다. 결과 집합을 보므로, <b>문제 항목을 빼는 요청</b>은
 * 결과가 규칙을 지키게 되어 통과한다 — 복구 경로가 자기 자신에게 막히지 않아야 한다.
 */
public class FilterWordSourceInvalidException extends ChatException {

    public FilterWordSourceInvalidException(String debugMessage, Throwable cause) {
        super(ChatErrorCode.FILTER_WORD_SOURCE_INVALID, debugMessage, cause);
    }
}
