package com.sapari.chat.domain.repository;

import java.time.Instant;
import java.util.Optional;
import java.util.UUID;

import com.sapari.chat.domain.model.ChatBan;

/**
 * 밴의 정본(Postgres). <b>블로킹</b> — 호출자가 live-app(MVC)이다.
 *
 * <p>Redis의 {@code chat:banned:} 키는 이 테이블의 미러다({@link ChatBanWriteRepository}). 판정은 미러가
 * 하지만 근거는 여기 있고, 미러가 날아가도 여기서 다시 만들 수 있다.
 */
public interface ChatBanStateRepository {

    /**
     * 이 사용자의 밴 판단을 <b>같은 잠금을 잡는 다른 트랜잭션에 대해</b> 혼자 하게 만든다.
     *
     * <p>단서가 붙는 이유는 이 잠금이 <b>협조적</b>이기 때문이다 — 같은 키로 이것을 부르는 트랜잭션만
     * 배제한다. {@code chat_ban}을 직접 읽거나 쓰는 다른 경로는 전혀 막지 못한다. 오늘 그 경로가
     * 하나뿐이라 성립하는 것이고, 그 전제를 강제하는 것은 아무것도 없다.
     *
     * <p>⚠️ <b>그래서 "잠금을 같이 잡아라"가 모든 처방이 되지는 않는다.</b> 예고된 수동 해제(행 DELETE)를
     * 만들 때 실제로 성립하는 어긋남은 이렇다 — ① 강퇴가 활성 밴을 보고 조기 반환하며 커밋하고 잠금을
     * 놓는다 ② 해제가 행을 지우고 미러를 지운다 ③ 그런데 ①의 호출자는 돌려받은 밴을 <b>커밋 뒤에</b>
     * 미러에 쓴다. 결과는 정본 없음 + 미러 존재, 즉 과다 차단이고 영구 밴이면 사람이 손대기 전까지
     * 풀리지 않는다. <b>해제가 이 잠금을 잡아도 막히지 않는다</b> — 그 미러 쓰기는 설계상 일부러 잠금
     * 밖(커밋 뒤)에 있다. 필요한 처방은 "같은 잠금"이 아니라 "미러 쓰기까지 포함하는 단위"다.
     * 조기 반환이 가장 흔한 경로라는 점이 특히 고약하다.
     *
     * <p>한때 이 자리에 다른 어긋남이 적혀 있었다 — 활성 밴 없음을 읽은 뒤 해제가 끼어들고
     * {@link #extendOrCreate}가 지운 밴을 되살린다는 것. <b>성립하지 않는다.</b> 쓰기 경로는 활성 밴이
     * 없을 때만 돌고, 밴이 없으면 해제가 지울 것도 없다.
     *
     * <p><b>왜 필요한가.</b> 승격은 "확증한 사람 수를 세고 → 임계와 견주고 → 쓴다"는 세 걸음인데,
     * 격리 수준이 READ COMMITTED라 세는 걸음에서 남의 미커밋 강퇴가 보이지 않는다. 서로 다른 방의 두
     * 운영자가 같은 사람을 동시에 강퇴하면 둘 다 "기존 + 나"만 세고, 합치면 임계를 넘겼는데 <b>둘 다
     * 임계 미달로 판단해 아무도 쓰지 않는다</b>(실측: 확증 1명 상태에서 둘이 겹치면 각자 2를 세고
     * 커밋 후 실제 3, 밴 0건).
     *
     * <p>{@link #extendOrCreate}의 단조 쓰기로는 막히지 않는다. 그쪽은 <b>둘 다 쓸 때</b> 짧은 쪽이
     * 긴 쪽을 덮지 않게 하는 장치이고, 여기서 잃는 것은 아무도 쓰지 않는 경우다 — 쓰기 규칙으로는
     * 닿을 수 없는 자리라 읽기부터 직렬화해야 한다.
     *
     * <p><b>영구히 잃는 것은 아니다.</b> 임계를 {@code >=}로 보기 때문에 다음 강퇴(확증 4)에서 1주가
     * 걸린다. 다만 그 다음 강퇴가 영영 오지 않으면 그 확증 3은 집행되지 않는다.
     *
     * <p><b>호출자가 트랜잭션을 열어야 하고, 세는 걸음보다 먼저 불러야 한다.</b> 잠금은 트랜잭션과 함께
     * 풀리므로 경계가 없으면 곧바로 풀려 아무것도 지키지 못한다.
     *
     * <p>경계 없이 부르면 <b>시끄럽게 죽는다</b> — 구현이 그것을 보장한다(실측:
     * {@code "No active transaction for update or delete query"}). 어떻게 보장하는지는 구현의 몫이고
     * 그 근거는 어댑터 javadoc에 있다. 한때 이 자리에 "조용히 0을 보호한다"고 적혀 있었고 그때는
     * 사실이었다 — 지금은 아니다.
     *
     * <p>⚠️ <b>이 잠금은 사용자 단위라 방이 달라도 줄을 세운다.</b> 그게 이 제약의 대가다 — 정상 보유
     * 시간은 밀리초고 경계 안에 외부 호출이 없지만, 호출자는 상한을 걸어 실패가 '대기'가 아니라
     * '재시도할 수 있는 예외'가 되게 해야 한다.
     */
    void lockForBanDecision(UUID userId);

    /**
     * 지금 유효한 밴. 만료가 없거나({@code expires_at IS NULL}) 아직 지나지 않은 행이다.
     *
     * <p><b>결과는 많아야 하나다</b> — 테이블에 유니크 제약({@code uk_chat_ban_user_id})이 있고, 갱신은
     * {@link #extendOrCreate}가 한다.
     *
     * <p>전에는 여기에 "여러 행 중 가장 오래 가는 것을 고른다"가 계약으로 적혀 있었다. <b>더는 아니다.</b>
     * 구현이 그 정렬을 뺐다 — 제약이 선 뒤로는 정렬이 결과를 가를 수 없어 어떤 테스트도 닿지 못했고,
     * 검증할 수 없는 방어는 다음 사람이 믿게 되는 문장일 뿐이라서다. 제약이 사라지면 이 메서드는 짧은
     * 쪽을 고르는 게 아니라 <b>결과가 둘이라며 던진다</b>({@code IncorrectResultSizeDataAccessException}).
     * 조용히 틀리는 대신 시끄럽게 죽는 쪽이고, 제약을 되돌린다면 그 변경이 정렬과 그것을 재는 테스트를
     * 함께 가져와야 한다.
     */
    Optional<ChatBan> findActive(UUID userId, Instant now);

    /**
     * 밴을 <b>늘리는 방향으로만</b> 남긴다 — 없으면 만들고, 있으면 더 긴 만료일 때만 늘린다.
     *
     * <p>덮어쓰기가 아닌 이유는 동시 강퇴 때문이다. 서로 다른 방에서 같은 사람을 동시에 강퇴하면 두
     * 호출이 각각 "활성 밴 없음"을 읽고 각각 쓰는데(READ COMMITTED라 서로의 미커밋 행이 안 보인다),
     * 나중에 도착한 쪽이 짧으면 그 사람은 정본에 한 달이 남아 있어도 일주일 뒤에 돌아온다.
     * 미러({@code chat:banned:})가 같은 이유로 이미 단조라, 정본이 다른 규칙을 쓰면 둘이 갈린다.
     *
     * <p><b>돌려주는 것은 지금 정본에 남아 있는 밴과, 이 호출이 그것을 바꿨는지다.</b> 이미 더 긴 밴이
     * 있으면 아무것도 바꾸지 않고 그 긴 밴이 돌아온다 — 실패가 아니다. 두 경우를 한 값으로 접으면
     * 호출자가 정본에 없는 만료를 "새로 걸었다"고 기록하게 되고, 그 기록에는 이 호출의 단계와 남의
     * 트랜잭션이 건 만료가 나란히 찍혀 서로 맞지 않는다.
     *
     * <p>⚠️ <b>이 포트로는 밴을 짧게 줄일 수 없다.</b> 관리자 감형은 행 삭제 후 재삽입이어야 하고,
     * <b>미러 삭제가 같은 변경에 함께 와야 한다</b> — 집행은 미러가 한다.
     *
     * <p>그때 지킬 것이 둘이다. <b>순서는 정본 → 미러</b>다. 중간에 끊기면 "정본은 풀렸는데 미러가
     * 남았다"(과다 차단)로 기울고, 반대 순서(미러 먼저)의 위험은 "밴이 풀린다"가 아니다 — 해제 작업에서
     * 그건 의도한 결과다. 위험은 <b>되살아나는 것</b>이다: 미러만 지우고 정본 삭제가 실패하면 남은 행이
     * 다음 강퇴 때 활성 밴으로 잡혀 미러에 다시 써진다. 정본을 먼저 지운 쪽의 잔여 상태(과다 차단)에는
     * 그런 자기 복원 경로가 없다.
     *
     * <p>다만 그 순서만으로는 부족하다. <b>미러 삭제를 정본 행의 존재로 게이팅하지 마라.</b> 정본을
     * 먼저 지운 뒤 미러 삭제가 실패했을 때, 재시도가 "지울 밴이 없다"로 끊기면 미러 삭제에 도달할
     * 코드가 영영 안 남는다. 없는 키를 지우는 것은 no-op이므로 해제 명령 전체가 몇 번을 다시 돌려도
     * 같은 결과여야 한다.
     *
     * <p>⚠️ <b>그 둘을 다 지켜도 동시 강퇴와는 어긋난다.</b> 강퇴의 조기 반환 경로가 커밋 <i>뒤에</i>
     * 미러를 다시 쓰므로, 그 사이에 해제가 끼면 지운 밴이 미러에만 되살아난다. {@link #lockForBanDecision}을
     * 해제에서 같이 잡아도 막히지 않는다 — 그 쓰기는 잠금 밖이다. 해제를 만들 때 정해야 하는 것은
     * 미러 쓰기까지 포함하는 단위이고, 그 판단이 이 포트 밖(유스케이스)에 있다.
     *
     * <p>⚠️ 과다 차단이 <b>스스로 풀리는 것은 기한부 밴뿐이다.</b> 영구 밴은 미러에 TTL 없이 쓰이므로,
     * 해제에서 미러 삭제가 빠지면 사람이 손대기 전까지 영구히 막힌다.
     *
     * <p><b>호출자가 트랜잭션을 열어야 한다.</b> 구현이 {@code @Modifying} 네이티브 INSERT라 경계가 없으면
     * {@code "No active transaction for update or delete query"}로 실패한다(실측). 이 포트는 경계를
     * 만들지 않는다 — 강퇴 흐름은 이 커밋이 확정된 <i>다음에</i> Redis로 넘어가야 하므로 경계가 어디서
     * 닫히는지가 설계의 일부이고, 그 판단은 유스케이스의 몫이다.
     */
    BanWrite extendOrCreate(ChatBan ban);

    /**
     * 쓰기의 결과.
     *
     * @param effective 이 호출 뒤 정본에 남아 있는 밴 — 미러에 실을 값이다
     * @param applied   이 호출이 실제로 정본을 바꿨는가. 거짓이면 이미 더 긴 밴이 있었다는 뜻이고,
     *                  그때 {@code effective}는 <b>남의 트랜잭션이 건 밴</b>이라 이 호출의 단계와 맞지 않는다
     */
    record BanWrite(ChatBan effective, boolean applied) {
    }
}
