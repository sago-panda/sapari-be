package com.sapari.chat.domain.exception;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

import com.sapari.common.core.exception.ErrorCode;

@Getter
@RequiredArgsConstructor
public enum ChatErrorCode implements ErrorCode {

    PERMISSION_DENIED(403, "CHAT-001", "채팅 권한이 없습니다."),
    RATE_LIMIT_EXCEEDED(429, "CHAT-002", "메시지를 너무 빠르게 보내고 있습니다."),
    USER_KICKED(403, "CHAT-003", "강퇴되어 채팅에 참여할 수 없습니다."),
    LIVE_NOT_ACTIVE(400, "CHAT-004", "진행 중인 라이브가 아닙니다."),
    // 사용자 잘못이 아니라 서버 쪽 상태의 문제라 5xx다. 어느 키가 문제인지는 응답이 아니라 로그로 간다
    // (BusinessException의 debugMessage가 로그용, 응답은 이 문구 — 내부 식별자 누출 방지).
    KICK_STORE_CORRUPTED(500, "CHAT-005", "강퇴 처리를 완료할 수 없습니다."),
    // 요청이 들고 온 방·대상·메시지가 서로 맞지 않는다. 요청자가 값을 정하므로 4xx다.
    // 문구가 세 갈래(메시지 없음·다른 방·다른 작성자)에 공통인 것은 의도다 — 어디까지 맞았는지를
    // 알려주면 방·메시지 id를 더듬는 통로가 된다. 어느 축이 어긋났는지는 debugMessage로 로그에만 간다.
    KICK_EVIDENCE_MISMATCH(400, "CHAT-006", "강퇴 증거를 확인할 수 없습니다."),

    // 강퇴(CHAT-003)와 갈라 둔다 — 강퇴는 그 방 하나이고 밴은 계정 전체라, 클라이언트가
    // "다른 방으로 가면 된다"를 안내할 수 있는지가 갈린다.
    USER_BANNED(403, "CHAT-007", "이용이 제한되어 채팅에 참여할 수 없습니다."),

    // 409인 이유: 서버가 고장난 게 아니라 같은 대상을 동시에 처리 중이라 지금은 완료할 수 없다는
    // 뜻이다. 5xx로 두면 정상적인 동시 강퇴가 알림을 울리고(전역 핸들러가 5xx만 스택까지 error로
    // 남긴다), 클라이언트에게는 재시도해도 소용없다는 신호로 읽힌다. 문구에 재시도를 담는다.
    KICK_CONTENDED(409, "CHAT-008", "다른 요청이 같은 사용자를 처리 중입니다. 잠시 후 다시 시도해 주세요."),

    // 이력 조회 입력이 계약을 어겼다. 도달 가능한 사유를 <b>열거만</b> 한다 — 개수를 적으면 사유가
    // 늘 때마다 그 수가 틀리고, 이 자리에서 "세 사유"→"네 사유" 로 이미 두 번 틀렸다:
    //   · 커서와 재생 위치를 동시에 지정
    //   · 음수 재생 위치
    //   · 재생 위치가 TTL 상한(730일)을 넘음
    //   · size 가 1~100 밖
    //   · 커서 형식이 ObjectId 가 아님(어댑터가 판정)
    // 이 코드가 따로 있는 이유: 명령 record 의 불변식은 IllegalArgumentException 으로 던지는데
    // 전역 핸들러에 그 타입 처리가 없어 <b>클라 잘못이 500 + "Unhandled exception" 로그</b>가 된다.
    // 전역 핸들러에 IllegalArgumentException 을 더하는 쪽은 저장소 전체의 응답을 바꾸므로(인프라 깊은
    // 곳에서 올라온 것까지 400 이 된다) 여기서 좁게 받는다.
    //
    // 문구가 사유들에 공통인 것은 의도가 아니라 <b>지금은 구분이 쓸모없기 때문</b>이다 — 전부
    // 클라이언트 코드의 버그이고 사용자가 고칠 것이 없다. 사유는 debugMessage 로 로그에만 남는다.
    HISTORY_QUERY_INVALID(400, "CHAT-009", "채팅 이력 조회 조건이 올바르지 않습니다."),

    // 보낸 항목이 사전 문을 통과하지 못했다 — 보이지 않는 글자, K 예산(길이) 초과, 또는 그 욕설을
    // 통째로 푸는 화이트리스트 항목. 요청자가 값을 정하므로 4xx다.
    //
    // ⚠️ 아래 FILTER_WORD_SOURCE_INVALID 와 <갈라 두는 것이 요점>이다. 서비스가 결과 사전 전체를
    // 검사하므로, 정본에 이미 규칙을 어기는 행이 있으면 운영자가 보낸 항목이 멀쩡해도 검사가
    // 떨어진다. 한 코드로 뭉개면 그때 "당신이 보낸 단어가 틀렸다" 는 <거짓 안내>가 나가고,
    // 운영자는 멀쩡한 단어를 고치려 든다.
    FILTER_WORD_REJECTED(400, "CHAT-010",
            "사전 항목이 규칙을 어겼습니다. 거부 사유는 서버 로그(requestId)에 있습니다."),

    // 정본에 이미 규칙을 어기는 항목이 있어 지금 상태로는 발행할 수 없다. 요청자 잘못이 아니고
    // 서버가 고장난 것도 아니라 409다 — 고치는 길이 있고(그 항목을 먼저 제거) 그 길이 이 API 다.
    //
    // 이 상태에 닿는 길은 둘이다: 정본을 직접 고친 쓰기(그래서 교체 지점에 게이트가 있다)와
    // <규칙을 나중에 조이는 것>. 두 번째가 더 중요하다 — K 예산을 64 에서 16 으로 내린 것이 바로
    // 그 변경이고, 테이블이 채워진 뒤에 같은 일을 하면 범위 밖 행 하나가 전파를 통째로 멈춘다.
    // 그 상태를 쓰기 시점에 드러내는 것이 이 코드의 존재 이유다.
    FILTER_WORD_SOURCE_INVALID(409, "CHAT-011",
            "사전 정본에 규칙을 어기는 항목이 있어 변경을 발행할 수 없습니다. "
                    + "그 항목을 먼저 제거해야 합니다 — 어느 항목인지는 서버 로그(requestId)에 있습니다."),

    // 느린 Mongo 가 저장을 끊었다. 사용자 잘못이 아니라 서버 상황이라 5xx 다. 문구에 "잠시 후" 를
    // 넣는 이유는 이 경우가 영구 실패가 아니기 때문이고, 어느 상한이 걸렸는지는 로그로만 간다
    // (응답에 내부 설정 키를 싣지 않는다 — 이 enum 의 다른 항목들과 같은 이유다).
    //
    // ⚠️ 이 코드는 **쓰기 갈래 전용**이다. 중복복구 재조회가 같은 상한에 끊겨도 이 코드로 올리지
    // 않는다 — 그 갈래의 전제가 DuplicateKey 라 문서가 이미 있고, 위 문구가 그 경우에 거짓이 된다.
    // 그 갈래는 번역 없이 5xx 로 가고 수만 chat.persist.timeout{stage=duplicate_recovery_read} 가
    // 센다(SPR-178). 갈래별 문구를 주려면 코드가 하나 더 필요하고 그건 와이어 계약 변경이다.
    // ⚠️ "저장하지 못했습니다" 가 아니다 — 클라이언트 상한은 서버 쓰기를 취소하지 않으므로
    // 저장됐을 수도 있다(실측: 상한 3ms·5ms 에서 예외인데 문서 1건). 그래서 결과를 단정하지 않는다.
    //
    // 이 문구는 WS 로 나가지 않는다 — WS 의 ERROR 프레임은 코드 문자열과 clientMsgId 만 싣고, 이 예외는
    // 거기서 INTERNAL 이 된다. 재시도 규칙은 그래서 modules/chat/AGENTS.md 의 "Retry contract" 에 있다:
    // 실패한 버블을 남겨 두고 <b>같은 clientMsgId 와 같은 본문</b>으로 다시 보낸다. 첫 쓰기가 남아 있었으면 유니크
    // 파셜 인덱스가 막고 그 메시지가 ACK 로 돌아온다. 새 UUID 로 보내면 중복이 생길 수 있다.
    PERSIST_TIMEOUT(503, "CHAT-012",
            "메시지 저장 결과를 확인하지 못했습니다. 잠시 후 이력을 확인해 주세요."),

    // 전송 판정(강퇴·밴·방 종료)을 읽지 못해 이번 전송을 받지 않았다. 저장 전에 거절하므로 같은
    // clientMsgId 로 다시 보내도 중복이 생기지 않는다. 그 판정이 닿지 않는 동안에는 실시간 전달도
    // 같은 Redis 라 함께 끊겨 있다 — 받아 두어도 보는 사람이 없고 검사 없이 이력에만 남는다.
    SEND_UNAVAILABLE(503, "CHAT-013", "지금은 메시지를 보낼 수 없습니다. 잠시 후 다시 보내 주세요."),

    // 같은 clientMsgId 로 이미 저장된 메시지와 본문이 다르다. 그대로 두면 서버가 먼저 저장된 메시지를
    // ACK 로 돌려줘 이번 본문이 사라진 채 성공으로 보고된다.
    //
    // 이 항목과 위 SEND_UNAVAILABLE 의 상태값·문구는 WS 로 나가지 않는다 — 전송은 WS 뿐이고, WS 의 ERROR
    // 코드는 핸들러가 예외 타입으로 만든다(UNAVAILABLE · CLIENT_MSG_ID_REUSED). 값은 다른 항목과 모양을
    // 맞춘 것이다.
    CLIENT_MSG_ID_REUSED(409, "CHAT-014", "같은 메시지 키로 다른 내용을 보낼 수 없습니다.");

    private final int status;
    private final String code;
    private final String message;
}
