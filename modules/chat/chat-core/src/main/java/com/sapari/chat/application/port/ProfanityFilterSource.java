package com.sapari.chat.application.port;

import com.sapari.chat.domain.rule.ProfanityFilter;

/**
 * 지금 유효한 욕설 필터를 내주는 포트 — <b>사전이 런타임에 바뀔 수 있기 때문에 있다.</b>
 *
 * <p>전에는 {@code SendChatService} 가 {@link ProfanityFilter} 를 생성자로 직접 받았다. 그러면
 * 빈을 교체해도 그 서비스에 안 닿는다 — 필드가 {@code final} 이고 서비스는 부팅 때 한 번 조립된다.
 * 사전을 바꾸는 유일한 길이 배포였던 이유가 그것이다.
 *
 * <p><b>필터는 계속 불변이다.</b> 교체는 <i>이 포트가 내주는 참조</i>를 바꾸는 것이고 필터 자체를
 * 고치는 것이 아니다. 그래야 트라이를 한 번만 빌드하고, 메시지를 처리하는 중에 자료구조가 바뀌지
 * 않는다 — 한 메시지는 자기가 집어 든 필터로 끝까지 간다(교체 순간에 걸친 메시지는 이전 사전이나
 * 다음 사전 중 <b>하나</b>를 쓰고, 섞인 상태를 보지 않는다).
 *
 * <p><b>왜 포트인가.</b> 바뀌는 참조를 들고 있는 것은 런타임 상태이고 도메인 규칙이 아니다.
 * 서비스는 "지금 것을 달라" 만 알고, 그것을 어디에 담아 어떻게 바꾸는지는 어댑터의 몫이다 —
 * 이 저장소가 Redis·Mongo에 쓰는 것과 같은 모양이다.
 *
 * <p><b>구현은 호출마다 멀쩡한 필터를 내줘야 한다.</b> {@code null} 을 내주면 마스킹이 그 순간
 * 조용히 꺼지고, 그건 이 도메인이 부팅 실패를 택해 막아 둔 상태다.
 */
public interface ProfanityFilterSource {

    /** 지금 유효한 필터. 매 메시지마다 불린다 — 구현이 무거우면 그게 그대로 전송 지연이 된다. */
    ProfanityFilter current();
}
