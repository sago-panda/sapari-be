package com.sapari.chat.application.port;

/**
 * 조회가 실패하면 <b>통과시키는</b> 모더레이션 판정 넷. fail-open 이 실제로 발화했는지를 가르는 태그다.
 *
 * <p>넷을 하나의 태그로 가르는 이유: 대응이 다르다. 종료 마커는 끝난 방에 글이 들어오는 것이고,
 * 강퇴·밴은 제재받은 사람이 돌아오는 것이다. 한 통에 담으면 후자가 전자의 평상시 잡음에 묻힌다.
 */
public enum ChatPolicy {

    /** 방 종료 마커 — 끝난 방 차단을 잃는다. */
    ROOM_ENDED,

    /** 강퇴 명단 — 그 방의 강퇴 집행을 잃는다. */
    KICK,

    /** 계정 밴 — 밴 집행을 잃는다. */
    BAN,

    /** 탈퇴 신청 기록 — 남은 룸 토큰으로의 재입장 차단을 잃는다. 입장에서만 본다. */
    WITHDRAWING
}
