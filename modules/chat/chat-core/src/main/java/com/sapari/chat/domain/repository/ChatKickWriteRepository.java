package com.sapari.chat.domain.repository;

import java.util.UUID;

/**
 * 강퇴 명단에 사람을 올리는 포트. <b>블로킹</b> — 호출자가 live-app(MVC)이다.
 *
 * <p>읽는 쪽은 {@link ChatKickRepository}(리액티브, streaming-app)다. 같은 Redis SET을 두 스택이 나눠
 * 쓰는 셈이라 키 문자열은 {@code infrastructure.redis} 패키지의 단일 소스가 계속 쥐고 있다 —
 * 읽는 쪽과 쓰는 쪽이 다른 키를 보게 되는 순간 강퇴는 조용히 통과한다.
 *
 * <p>이 SET은 <b>집행 캐시</b>다. 정본은 {@link ChatKickLogRepository}(Postgres)이고, 그래서 순서가
 * 정해져 있다 — 로그가 커밋으로 확정된 <i>다음에</i> 여기 올린다. 반대로 하면 롤백된 강퇴가 Redis에만
 * 남아 근거 없이 사람을 막는다.
 */
public interface ChatKickWriteRepository {

    /**
     * 이 방의 강퇴 명단에 올린다. 이미 있어도 그대로 성공이다(집합이라 두 번 넣어도 하나다).
     *
     * <p><b>만료를 함께 걷어낸다.</b> 방이 끝날 때 이 키에는 회수용 만료가 붙는데, 그 신호가 잘못 온
     * 것이었다면 방송은 계속되고 키에는 만료만 남아 있다. 그 상태에서 새로 강퇴를 올리면 — Redis의
     * 집합 추가는 남아 있는 만료를 건드리지 않으므로 — 명단 전체가 만료 시각에 조용히 사라지고
     * 강퇴됐던 사람이 전원 돌아온다. 그래서 올릴 때마다 만료를 떼어 낸다.
     *
     * <p><b>대칭 케이스가 하나 남는다.</b> 방이 <i>정상</i>으로 끝난 뒤 늦게 도착한 등록(재시도, 종료와
     * 겹친 요청)도 같은 이유로 만료를 떼어 내는데, 그 방에는 다시 만료를 걸어 줄 사람이 없다 — 회수는
     * 종료 신호 한 번뿐이다. 그러면 그 키는 영구히 남는다. 여기서 종료 여부를 보고 갈라내지 <b>않는</b>
     * 이유는, 오발행된 종료 신호도 같은 마커를 남기기 때문이다 — 마커를 근거로 만료를 존치시키면
     * 위 문단의 조용한 소멸이 그대로 돌아온다. 막을 자리는 여기가 아니라 상류다: 강퇴 유스케이스가
     * 방을 정본(DB)에서 읽어 진행 중이 아니면 거부하면, 늦은 등록 자체가 오지 않는다.
     *
     * <p>실패는 삼키지 않고 전파한다. 여기서 실패하면 그 사람은 재접속으로 곧장 돌아오므로,
     * 호출자가 강퇴를 실패로 처리하고 다시 시도할 수 있어야 한다. 키가 우리 타입이 아니어서 나는
     * 실패만 {@code KickStoreCorruptedException}으로 갈라 던진다 — 그건 재시도로 낫지 않는다.
     */
    void register(UUID roomId, UUID userId);

    /**
     * 정본에서 읽은 명단으로 이 방의 집행 명단을 <b>맞춰 놓는다</b> — 키 상태에 따라 둘로 갈린다.
     *
     * <p><b>왜 필요한가.</b> 이 키는 집행 캐시이고 정본은 {@code chat_kick_log} 다
     * ({@link ChatKickRepository#expireAfterRoomEnded} javadoc). 그런데 되살리는 코드가 없어서
     * "만료라서 복구 가능" 이 <b>사람이 손으로 Redis 를 만질 때만</b> 성립했다. 키가 사라지거나
     * ({@code maxmemory} 축출, replica 승격 — 정본 L11) 우리 타입이 아닌 값으로 오염되면
     * ({@code KickStoreCorruptedException}) 그 방의 강퇴 집행이 <b>조용히, 영구히</b> 꺼진다.
     * 읽기 경로가 fail-open 이라 아무도 막히지 않고, 로그 한 줄만 남는다.
     *
     * <p><b>계약 — 세 줄이다.</b>
     * <ul>
     *   <li><b>건강한 키(집합이거나 없음)에는 더한다.</b> 지우지 않는다. 멤버가 하나라도 들어가면
     *       만료를 걷는다({@code PERSIST}) — 회수 만료가 붙은 키에 더하면 되살린 명단이 그 시각에
     *       통째로 사라지기 때문이다.
     *   <li><b>오염된 키는 지우고 다시 세운다.</b> 타입이 틀린 키에는 {@code SADD} 가 애초에 들어가지
     *       못하고, 그게 이 메서드가 닫으려는 가장 나쁜 경우다. 거기서 지워도 잃는 것은 없다 —
     *       그 내용은 우리가 읽을 수 없는 값이었다.
     *   <li><b>둘 다 한 실행이다.</b> 나누면 판정과 쓰기 사이에 키 상태가 바뀌어, 오염으로 판정한
     *       키를 지운 뒤 그 사이에 들어온 정당한 등록까지 함께 날릴 수 있다. 멤버가 많아도 왕복은
     *       하나다.
     * </ul>
     *
     * <p><b>왜 더하기인가 — 이것이 이 포트의 가장 중요한 결정이다.</b> 처음에는 "통째로 다시 세운다"
     * 였고 그게 결함이었다. 강퇴는 DB-first 라(로그 커밋 확정 → {@code SADD}) 재적재가 정본을 읽은
     * <i>뒤</i> 커밋된 강퇴가 그 {@code DEL} 에 지워졌다 — 읽기 경로가 fail-open 이고 재시도 경로가
     * 없어 <b>영구</b>다. 복구하려 부른 조치가 집행을 지운다.
     * 더하기가 충분한 이유는 집합의 방향이 한쪽이기 때문이다: 멤버를 넣는 것은 강퇴뿐이고 강퇴는
     * 로그를 먼저 커밋하므로 앱 경로에서 <b>{@code SET ⊆ 정본}</b> 이 늘 참이다. 반대(정본에 없는데
     * SET 에 있음)를 만드는 경로가 없으니 지울 것이 없다.
     *
     * <p><b>빈 정본은 "지워라" 가 아니다.</b> 건강한 키에 빈 명단으로 부르면 <b>아무 일도 일어나지
     * 않는다</b>(실측: 기존 2명 + TTL 24h → {@code SCARD 2} · {@code TTL 86400} 유지). 그게 맞는
     * 동작이다 — "그 방에 강퇴가 없다" 와 "읽은 시점에 아직 없었다" 를 구분할 수 없으므로, 둘 중
     * 지우는 쪽을 고르면 위의 영구 삼킴이 다른 문으로 돌아온다.
     *
     * <p><b>멱등이다.</b> 정본이 같으면 몇 번을 불러도 결과가 같다. 정본이 입력이므로 이 호출로는
     * 정본에 없는 사람을 명단에 올릴 수 없다 — <b>과다 차단</b>을 새로 만들 수 없다. 반대 방향
     * (정당한 집행을 지우는 것)은 위 더하기 결정이 막는다. 한때 이 javadoc 이 앞쪽만 선언하고
     * 뒤쪽을 적지 않아서, 지우는 구현이 계약을 어기지 않는 것처럼 보였다.
     *
     * <p><b>끝난 방에는 부르지 않는다</b> — 호출자의 책임이다({@code ReconcileKickListService} 가
     * live 정본을 읽어 거부한다). 끝난 방에 더하면 {@code PERSIST} 가 회수 만료를 걷어내고
     * 다시 붙여 줄 경로가 없다. 그 처방은 위 {@link #register} javadoc 이 대칭 케이스에 대해
     * 이미 적어 둔 것과 같다("막을 자리는 여기가 아니라 상류다").
     *
     * <p>실패는 그대로 던진다. 복구하지 못했다는 사실이 호출자에게 가야 한다.
     *
     * <p><b>고치기 전의 타입을 돌려준다.</b> 오염은 이 경로에서 보고할 실패가 아니지만(고치려는
     * 대상이다) <b>사실은 잃지 않아야 한다</b> — "키가 타입이 틀려 있었다" 는 그 방의 강퇴 집행이
     * 꺼져 있었다는 직접 증거이고, 이 조치를 운영자 전용으로 둔 근거가 그 가청성이다.
     * {@code DEL} 뒤에는 알 수 없으므로 어댑터가 그 앞에서 읽어야 한다.
     *
     * @param kickedUserIds 정본에서 읽은 그 방의 강퇴자 전체. 비어 있으면 아무 일도 하지 않는다.
     *                      <b>무계</b>다 — 어댑터가 크기에 기대어 깨지지 않아야 한다
     * @return 고치기 전 키가 우리 타입이 아니었는가
     */
    boolean reconcile(UUID roomId, java.util.Collection<UUID> kickedUserIds);
}
