package com.sapari.chat.application.port;

/**
 * 서버가 세션을 끊은 사유.
 *
 * <p>이 열거가 존재하는 이유는 <b>와이어에서 셋이 구분되지 않기 때문이다</b> — 방 종료·수명 만료·
 * 생존 실패가 전부 close 1000 이고, 그중 방 종료만 직전에 설명 프레임을 보낸다. 밖에서 보면
 * "정상 종료가 늘었다" 로만 보이므로, 어느 쪽이 늘었는지는 여기서만 읽을 수 있다.
 */
public enum SessionCutReason {

    /** 방송이 끝났다. 정상이고, 방송 수와 함께 움직여야 한다. */
    ROOM_ENDED,

    /** 세션 수명 상한. 지터가 있어 고르게 퍼져야 한다 — 몰려 있으면 지터가 안 듣는다는 신호다. */
    LIFETIME,

    /** 생존 확인 실패. 늘면 네트워크나 아웃바운드 적체를 본다. */
    LIVENESS,

    /** 아웃바운드 버퍼 초과(close 1013). 느린 클라이언트를 힙 잠식 전에 끊은 것이다. */
    BUFFER_OVERFLOW,

    /**
     * 강퇴·밴 집행(close 1008). 이 값이 없으면 사유의 합이 서버 주도 종료 전체와 맞지 않아,
     * 종료율을 보는 사람이 설명되지 않는 차이를 쫓게 된다.
     */
    MODERATION
}
