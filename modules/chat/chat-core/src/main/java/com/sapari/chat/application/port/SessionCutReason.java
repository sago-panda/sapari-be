package com.sapari.chat.application.port;

/**
 * 서버가 세션을 끊은 사유.
 *
 * <p>이 열거가 존재하는 이유는 <b>와이어에서 구분되지 않기 때문이다</b> — 방 종료·수명 만료·
 * 생존 실패가 전부 close 1000 이고, 제재와 탈퇴가 전부 close 1008 이다. 밖에서 보면 "정상 종료가
 * 늘었다" 로만 보이므로, 어느 쪽이 늘었는지는 여기서만 읽을 수 있다.
 *
 * <p>⚠️ <b>이 사유들의 합은 서버 주도 종료 전체가 아니다.</b> 한때 그렇게 적혀 있었는데 거짓이다 —
 * 적어도 넷이 이 미터에 안 들어온다: 입장 거부 {@code KICKED}·{@code BANNED}·{@code ROOM_ENDED}
 * (세션이 성립하기 전이라 {@code EntryGate} 가 지표 없이 거부한다. 거부 중 상한 초과만
 * {@code chat.sessions.admission_capped} 로 따로 세어진다) 과 프레임 상한 초과(close 1009 —
 * 그것을 보내는 것은 전송 계층이라 chat 코드에 볼 자리가 없다). 종료율을 이 합으로 설명하려 하면
 * 설명되지 않는 차이를 쫓게 되므로, <b>이 미터는 성립한 세션이 서버 판단으로 끊긴 수</b>로만 읽는다.
 */
public enum SessionCutReason {

    /** 방송이 끝났다. 정상이고, 방송 수와 함께 움직여야 한다. */
    ROOM_ENDED,

    /** 세션 수명 상한. 지터가 있어 고르게 퍼져야 한다 — 몰려 있으면 지터가 안 듣는다는 신호다. */
    LIFETIME,

    /** 생존 확인 실패. 늘면 네트워크나 아웃바운드 적체를 본다. */
    LIVENESS,

    /** 아웃바운드 버퍼 초과(close 1013). 느린 클라이언트를 힙 잠식 전에 끊은 것이다. */
    BUFFER_OVERFLOW,

    /** 강퇴·밴 집행(close 1008). 제재율로 읽히는 값이다. */
    MODERATION,

    /**
     * 계정 탈퇴 신청(close 1008). <b>제재가 아니다</b> — 사용자가 스스로 누른 것이다.
     *
     * <p>{@link #MODERATION} 과 close 코드가 같고 사유가 다르다. 전에는 둘이 같은 값을 썼는데,
     * 그러면 탈퇴가 제재율을 부풀린다 — 그리고 그 부풀림은 close 코드로 가려낼 수 없다.
     * {@code SystemMessageCode.WITHDRAWING} 의 javadoc 이 탈퇴가 제재와 달라야 한다는 것을
     * 이미 적고 있으므로, 합치는 쪽이 저장소 자기 기준에 대고 틀린 것이었다.
     */
    WITHDRAWN
}
