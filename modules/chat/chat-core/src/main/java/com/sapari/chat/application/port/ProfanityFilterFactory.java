package com.sapari.chat.application.port;

import java.util.Set;

import com.sapari.chat.domain.rule.ProfanityFilter;

/**
 * 두 집합을 <b>사전의 문</b>에 통과시켜 필터로 만든다.
 *
 * <p><b>문이 포트인 이유.</b> 사전은 세 입구로 들어온다 — 번들 리소스 · 설정 CSV · 정본 스냅샷.
 * 앞의 둘은 부팅 때 호스트 앱이 직접 들여보내지만 세 번째는 런타임에 전파돼 오고, 그것을 받는
 * 쪽은 <b>같은 검사</b>를 지나야 한다: 보이지 않는 글자가 든 항목은 평범한 입력을 영원히 못
 * 잡고(막은 것처럼 보인다), 예산을 넘는 항목 하나는 함대 처리량을 떨어뜨리고, 욕설 그 자체인
 * 화이트리스트 항목 하나는 그 욕설을 사전 전체에서 푼다.
 *
 * <p>그 검사의 구현(리소스 파싱·정규화·유니코드 분류)은 어댑터의 몫이라 여기서는 결과만 받는다.
 *
 * <p><b>거부는 예외다.</b> 호출자가 그것을 잡아 <b>교체를 포기하고 이전 필터를 계속 쓴다</b> —
 * 부팅 입구가 부팅을 세우는 것과 방향이 다른데, 도는 Pod 을 사전 한 줄의 오타로 죽이는 것이
 * 그 오타보다 나쁘기 때문이다.
 */
public interface ProfanityFilterFactory {

    /**
     * 사전 항목을 로그 한 줄에 나열할 때의 상한 — <b>이 수를 쓰는 두 자리의 단일 소스</b>다.
     *
     * <p>상한이 없을 때 전량이 걸리면 한 줄이 35,966자였다(측정: 욕설 1,078 · 화이트리스트 38).
     * 평시에는 0건이라 안 드러나는데, 접기 평면을 바꾸는 변경이나 화이트리스트 경고 하나가
     * 들어오면 그 줄이 발행·교체마다 나간다.
     *
     * <p>쓰는 자리가 레이어를 가로지르므로 상수를 공유할 자리가 이 포트뿐이다 — 전수 다섯
     * (2026-11-05): {@code application/service} 의 그림자 보고 · {@code infrastructure/config} 의
     * 요약 · streaming-app 의 설정 WARN 테스트 · 그리고 사전 테스트 둘. 각자 20 을 적어 두면
     * 한쪽만 바뀌는 드리프트가 되고, 이 브랜치가 그 모양을 네 번 밟았다. 테스트 면도 참조해야
     * 한다 — 참조가 main 에만 있던 동안 상한을 내리면 프로덕션은 따라가고 테스트만 갈렸다.
     */
    int LOG_ENTRY_LIMIT = 20;

    /**
     * @param origin 실패 메시지에 실을 출처 이름(예: {@code "chat:dict"}). 세 입구 중 어디서
     *               떨어졌는지가 당직자에게 가야 한다
     * @throws IllegalStateException 항목이 문을 통과하지 못했을 때. 메시지에 무엇이 왜
     *         떨어졌는지가 들어 있어야 한다 — 호출자가 그것을 로그에 그대로 싣는다
     */
    ProfanityFilter from(String origin, Set<String> words, Set<String> whitelist);

    /**
     * 항목을 이 문이 보는 평면으로 접는다 — <b>저장하는 쪽이 쓸 값</b>이다.
     *
     * <p>문이 접은 값을 검사하는데 쓰기가 원문을 저장하면 한 요청에서 두 결과가 나온다.
     * 그래서 이 평면이 포트에 있다: 검사하는 쪽과 저장하는 쪽이 <b>같은 구현</b>에서 값을
     * 받아야 하고, 둘이 갈리면 저장된 것과 집행되는 것이 달라져 삭제가 성립하지 않는다.
     *
     * <p>접은 결과가 비어 있을 수 있다(공백만 들어온 경우). 그 판정은 호출자가 한다 —
     * 이 메서드는 평면 변환이고 정책이 아니다.
     */
    String normalize(String word);

    /**
     * 항목을 <b>당직자가 지목할 수 있는 모양</b>으로 찍는다 — 보이지 않는 글자만
     * {@code \\uXXXX} 로 바꾸고 나머지는 그대로 둔다.
     *
     * <p>이것이 포트에 있는 이유는 같은 렌더링이 이미 사전 문의 거부 메시지에 있기 때문이다.
     * 호출자가 각자 찍으면 둘이 갈리고, 한쪽이 전체를 코드 포인트로 펼쳐 <b>보이는 글자까지</b>
     * 로그로 내보내는 일이 벌어졌다(그렇게 재발명된 것을 이 메서드가 대체한다).
     *
     * <p>⚠️ 이 결과는 <b>원문으로 되돌릴 수 있다.</b> 가리기가 아니고, 가려서도 안 된다 —
     * 이것을 쓰는 자리의 복구 수단이 "그 행을 직접 지우기" 이고 그러려면 정확한 값이 필요하다.
     * 그 예외를 쓰는 쪽이 자기 자리에 적는다.
     */
    String describe(String word);
}
