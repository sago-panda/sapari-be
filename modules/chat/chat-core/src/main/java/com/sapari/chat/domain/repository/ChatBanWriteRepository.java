package com.sapari.chat.domain.repository;

import java.time.Instant;
import java.util.UUID;

/**
 * 밴 미러 쓰기({@code chat:banned:{userId}}). <b>블로킹</b> — 호출자가 live-app(MVC)이다.
 *
 * <p>읽는 쪽은 {@code ChatBanRepository}(리액티브, streaming-app)이고 키의 <b>존재</b>만 본다. 그래서
 * 여기서도 값에 의미를 담지 않는다 — 만료는 TTL이 표현하고, 영구 밴은 TTL을 붙이지 않는다.
 *
 * <p><b>모든 쓰기가 변경 번호를 싣는다.</b> 번호는 정본 쪽이 사용자별 잠금 안에서 집고
 * ({@link ChatBanStateRepository#nextChangeVersion}), 미러는 그 사용자에 대해 본 것 중 가장 큰 번호
 * 이하인 쓰기를 거절한다. 미러 반영이 커밋 뒤 잠금 밖이라 도착 순서가 커밋 순서와 다를 수 있어서다 —
 * 번호가 없으면 "적용 커밋 → 해제 커밋 → 해제 삭제 → 적용 쓰기" 순서로 도착할 때 풀린 밴이 미러에
 * 되살아나고, 영구 밴이면 스스로 사라지지도 않는다.
 *
 * <p>실패는 삼키지 않고 던진다. 미러에 못 쓴 밴은 아무도 막지 못하는 밴이라, 호출자가 실패로 처리하고
 * 재시도할 수 있어야 한다.
 */
public interface ChatBanWriteRepository {

    /**
     * 밴을 미러에 반영한다. <b>늦게 온 번호는 거절하고, 만료는 늘어나기만 한다.</b>
     *
     * <p>이미 걸린 밴보다 짧은 만료는 <b>반영되지 않는다</b>(무동작). 만료 없는 영구 밴은 어떤 기한부
     * 밴으로도 덮이지 않는다.
     *
     * <p><b>늘리기 전용은 구현 편의가 아니라 계약이다.</b> 서로 다른 방에서 같은 사람을 동시에 강퇴하면
     * 두 호출자가 각각 밴을 만들어 각자 여기에 쓴다. 덮어쓰는 구현이면 나중에 도착한 쪽이 이겨 짧은
     * TTL이 남고, 집행은 이 미러가 하므로 그 사람은 정본에 한 달이 남아 있어도 일주일 뒤에 돌아온다.
     *
     * <p>⚠️ <b>그래서 이 메서드로는 밴을 줄이거나 풀 수 없다.</b> 해제는 {@link #releaseMirror}다.
     *
     * @param expiresAt 만료 시각. {@code null}이면 영구라 TTL을 붙이지 않는다
     * @param version   정본 잠금 안에서 집은 변경 번호
     * @return 무엇이 일어났는가 — 호출자가 늦은 쓰기({@link MirrorApply#STALE})를 다른 결과와 가른다
     */
    MirrorApply ban(UUID userId, Instant expiresAt, Instant now, long version);

    /**
     * 미러를 지운다 — 정본 행의 존재를 묻지 않고, <b>번호만 묻는다.</b>
     *
     * <p>{@link #ban}이 늘리기 전용이라 짧은 만료로는 아무것도 바꿀 수 없고, 영구 밴은 TTL이
     * 없어 스스로 풀리지도 않는다. 그래서 해제에는 이 삭제가 반드시 있어야 한다.
     *
     * <p><b>정본 행의 존재를 묻지 않는다.</b> 해제는 정본을 먼저 지우므로 재시도 때는 이미 행이
     * 없는데, 거기서 "지울 밴이 없다" 로 끊으면 미러에 도달할 코드가 안 남는다. 재시도는 새 번호를
     * 집으므로 번호 검사에 막히지 않는다.
     *
     * <p>번호를 묻는 이유는 반대 방향의 같은 경쟁이다 — 해제 뒤에 새로 걸린 밴이 먼저 미러에 닿고
     * 해제 삭제가 늦게 오면, 번호가 없을 때 새 밴이 지워진다.
     *
     * <p>실패는 삼키지 않고 던진다 — 미러가 남은 해제는 아무도 풀지 못한 해제다.
     *
     * @return 실제로 삭제를 실행했는가. 거짓이면 더 새 변경이 이미 미러에 닿아 있었다
     */
    boolean releaseMirror(UUID userId, long version);

    /** {@link #ban}의 결과. */
    enum MirrorApply {
        /** 이 번호보다 새 변경(적용이든 해제든)이 이미 미러에 닿았다. 아무것도 바꾸지 않았다. */
        STALE,
        /** 번호는 새것이지만 이미 같거나 더 긴 밴이 있었다(또는 만료가 이미 지났다). */
        UNCHANGED,
        /** 있던 밴을 더 길게 늘렸다. */
        EXTENDED,
        /** 미러에 밴이 없었고 새로 썼다 — 재적재에서는 이것이 정본과 미러가 어긋났던 사용자다. */
        CREATED
    }
}
