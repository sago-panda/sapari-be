package com.sapari.chat.application.port;

/**
 * 연산 상한이 영속을 끊은 자리. <b>두 갈래의 확신 수준이 달라 한 수로 세면 안 된다</b> —
 * 한쪽은 결과가 불명이고 한쪽은 존재가 확정이다.
 *
 * <p>{@link DeliveryStage} 와 짝지어 읽지 말 것 — 그쪽은 "영속됐고 전달만 잃었다" 이고 이쪽은
 * 영속 자체가 끊긴 축이다.
 */
public enum PersistStage {

    /**
     * 메시지 저장이 끊겼다 — <b>남았는지 알 수 없다</b>.
     *
     * <p>⚠️ 한때 이 자리가 "아무 데도 남지 않았다" 로 단정했고 거짓이었다. 클라이언트 쪽 상한은
     * 서버의 쓰기를 취소하지 않는다 — 실측(mongo:7.0 · 드라이버 5.6.5): 상한 1ms·2ms 에서는 예외 +
     * 문서 0건, 3ms·5ms 에서는 예외 + 문서 1건이고 <b>두 갈래가 같은 예외 클래스</b>다.
     *
     * <p>⚠️ 발신자가 아는 것은 <b>에러가 났다</b>는 사실이지 "저장되지 않았다" 가 아니다. 그 둘을
     * 섞어 적었던 자리가 열거에서 빠져 있었고(이 파일이 그 자리다), 당직자가 런북의
     * {@code stage=write} 를 따라 정의로 내려오면 닿는 문장이 여기다. 규모는 이 값으로만 보인다.
     */
    WRITE,

    /**
     * {@code DuplicateKey} 뒤 기존 메시지를 되읽다 끊겼다 — 그 문서는 <b>이미 있다</b>.
     *
     * <p>{@link #WRITE} 와 섞으면 이력에 남아 있는 메시지를 유실로 보고한다. 발신자가 받는 것은
     * 번역되지 않은 5xx 이고, 다시 보내면 같은 {@code clientMsgId} 라 또 이 갈래로 온다 — 즉 이
     * 값이 오르는 동안 그 사용자는 <b>이미 저장된 자기 메시지를 확인할 수 없다</b>.
     */
    DUPLICATE_RECOVERY_READ
}
