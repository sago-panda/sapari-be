-- 밴 미러(Redis chat:banned:{userId})에 가는 변경의 순서 번호.
--
-- 적용과 해제는 사용자별 어드바이저리 잠금(ChatKickRecorder · ChatBanReleaseRecorder) 안에서 정본을
-- 바꾸지만, 미러 반영은 커밋 <뒤>에 잠금 밖에서 일어난다. 그래서 "적용 커밋 → 해제 커밋 → 해제 DEL →
-- 적용 SET" 순서로 도착하면 풀린 밴이 미러에 되살아나고, 영구 밴이면 스스로 사라지지도 않는다.
--
-- 이 시퀀스 값을 잠금 안에서 집어 미러 쓰기에 싣는다. 같은 사용자에 대해서는 잠금이 직렬화하므로
-- 커밋 순서와 번호 순서가 같고, 미러는 자기가 본 마지막 번호 이하의 쓰기를 거절한다.
-- 시계가 아니라 시퀀스인 이유: 파드마다 시계가 다르면 잠금 순서와 시각 순서가 갈린다.
