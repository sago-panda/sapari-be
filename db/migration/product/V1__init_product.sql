COMMENT ON TABLE product_schema.option_attribute_group_presets IS '속성 그룹별 사전 정의 값 목록 (드롭박스 선택지)';
COMMENT ON COLUMN product_schema.option_attribute_group_presets.attribute_group_id IS 'ref: option_attribute_groups.id';
