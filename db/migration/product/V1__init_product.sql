-- 상품 원장. 정렬·필터용 캐시 컬럼은 앱이 갱신 책임
CREATE TABLE product_schema.products
(
    id                      uuid          NOT NULL DEFAULT gen_random_uuid(),
    seller_id               uuid          NOT NULL, -- ref: users.id
    category_id             bigint        NOT NULL, -- ref: categories.id
    name                    varchar(255)  NOT NULL,
    description             text,                   -- 상세 설명 (최대 30,000자)
    base_price              integer       NOT NULL, -- 목록 표시용 시작 가격
    status                  varchar(20)   NOT NULL DEFAULT 'PENDING_REVIEW', -- ENUM: PENDING_REVIEW, ON_SALE, SUSPENDED, REJECTED
    shipping_policy_id      uuid,                   -- ref: seller_shipping_policies.id (NULL=판매자 기본 정책)
    additional_shipping_fee integer       NOT NULL DEFAULT 0, -- 상품 단독 배송비. 0 초과 시 판매자 정책 무시
    rejection_reason        text,                   -- 검수 반려 사유
    deleted_at              timestamptz,            -- 논리 삭제 일시
    min_price               integer,                -- 할인 후 최저 조합 가격. NULL=재고 조합 없음. 앱이 갱신
    has_stock               boolean       NOT NULL DEFAULT true, -- 재고 있는 조합 존재 여부. 앱이 갱신
    purchase_count          integer       NOT NULL DEFAULT 0, -- 누적 구매 완료 수 (구매인기순)
    avg_rating              numeric(3, 1),          -- 평균 별점 캐시. NULL=리뷰 없음
    review_count            integer       NOT NULL DEFAULT 0,
    view_count              integer       NOT NULL DEFAULT 0, -- 상품 상세 조회 수 (Redis 버퍼링 후 반영)
    wishlist_count          integer       NOT NULL DEFAULT 0,
    option_model            varchar(20)   NOT NULL DEFAULT 'COMBINATION', -- ENUM: COMBINATION, COMPONENT, HYBRID
    search_indexed_at       timestamptz,            -- ES 마지막 인덱싱 일시
    created_at              timestamptz   NOT NULL,
    updated_at              timestamptz   NOT NULL,
    CONSTRAINT pk_products PRIMARY KEY (id)
);
CREATE INDEX ON product_schema.products (seller_id, status, deleted_at);
CREATE INDEX ON product_schema.products (category_id, status, deleted_at);
CREATE INDEX ON product_schema.products (status, deleted_at, min_price);      -- 가격순 정렬
CREATE INDEX ON product_schema.products (status, deleted_at, purchase_count); -- 인기순 정렬 (구매수)
CREATE INDEX ON product_schema.products (status, deleted_at, avg_rating);     -- 별점순 정렬
CREATE INDEX ON product_schema.products (status, deleted_at, wishlist_count); -- 찜순 정렬
CREATE INDEX ON product_schema.products (status, deleted_at, view_count);     -- 조회순 정렬
CREATE INDEX ON product_schema.products (status, created_at);
CREATE INDEX ON product_schema.products (shipping_policy_id);
CREATE INDEX ON product_schema.products (option_model);
CREATE INDEX ON product_schema.products (search_indexed_at)
    WHERE search_indexed_at IS NULL OR search_indexed_at < updated_at;        -- stale 후보

COMMENT ON TABLE product_schema.products IS '상품 원장. 정렬·필터용 캐시 컬럼(min_price·has_stock·purchase_count·avg_rating·review_count·view_count·wishlist_count)은 앱이 갱신 책임';
COMMENT ON COLUMN product_schema.products.seller_id IS 'ref: users.id';
COMMENT ON COLUMN product_schema.products.category_id IS 'ref: categories.id';
COMMENT ON COLUMN product_schema.products.description IS '상세 설명 (최대 30,000자)';
COMMENT ON COLUMN product_schema.products.base_price IS '목록 표시용 시작 가격. 옵션 없는 상품은 결제 금액과 동일';
COMMENT ON COLUMN product_schema.products.status IS 'ENUM: PENDING_REVIEW, ON_SALE, SUSPENDED, REJECTED. 삭제는 deleted_at으로 처리';
COMMENT ON COLUMN product_schema.products.shipping_policy_id IS 'ref: seller_shipping_policies.id. NULL=판매자 기본 정책 적용';
COMMENT ON COLUMN product_schema.products.additional_shipping_fee IS '상품 단독 배송비. 0 초과 시 판매자 정책 무시하고 이 금액만 적용';
COMMENT ON COLUMN product_schema.products.rejection_reason IS '검수 반려 사유';
COMMENT ON COLUMN product_schema.products.deleted_at IS '논리 삭제 일시';
COMMENT ON COLUMN product_schema.products.min_price IS '할인 후 최저 조합 가격 = MIN(COALESCE(cwd.final_price, poc.price)). NULL=재고 조합 없음. 앱이 갱신. 라이브 특별가 미반영';
COMMENT ON COLUMN product_schema.products.has_stock IS '재고 있는 조합 존재 여부 = EXISTS((stock - reserved_stock) > 0 AND is_available). 앱이 갱신';
COMMENT ON COLUMN product_schema.products.purchase_count IS '누적 구매 완료 수 (구매인기순). deliveries.status=DELIVERED 전환 시 +1';
COMMENT ON COLUMN product_schema.products.avg_rating IS '평균 별점 캐시. NULL=리뷰 없음. review 변경 시 갱신';
COMMENT ON COLUMN product_schema.products.review_count IS '리뷰 수 캐시';
COMMENT ON COLUMN product_schema.products.view_count IS '상품 상세 조회 수 (조회순 정렬). Redis 버퍼링 후 반영';
COMMENT ON COLUMN product_schema.products.wishlist_count IS '찜 수 캐시 (찜순 정렬). wishlists 추가/취소 시 앱이 갱신';
COMMENT ON COLUMN product_schema.products.option_model IS 'ENUM: COMBINATION, COMPONENT, HYBRID. 현재 COMBINATION 고정';
COMMENT ON COLUMN product_schema.products.search_indexed_at IS 'ES 마지막 인덱싱 일시. 동기화 lag 모니터링';

