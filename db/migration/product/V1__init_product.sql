    description varchar(255),
    created_at  timestamptz NOT NULL,
    updated_at  timestamptz NOT NULL,
    CONSTRAINT pk_option_attribute_groups PRIMARY KEY (id)
);
CREATE INDEX ON product_schema.option_attribute_groups (is_system);
CREATE INDEX ON product_schema.option_attribute_groups (seller_id);

COMMENT ON TABLE product_schema.option_attribute_groups IS '옵션 속성 그룹 템플릿. 관리자 공용 + 판매자 커스텀 구분';
COMMENT ON COLUMN product_schema.option_attribute_groups.name IS '속성 그룹명 (예: 색상, 사이즈, RAM)';
COMMENT ON COLUMN product_schema.option_attribute_groups.is_system IS 'true=관리자 공용, false=판매자 커스텀';
COMMENT ON COLUMN product_schema.option_attribute_groups.seller_id IS 'ref: users.id (커스텀 생성 판매자, 시스템은 NULL)';
COMMENT ON COLUMN product_schema.option_attribute_groups.description IS '그룹 설명';

