-- 상품·옵션 이미지 통합(폴리모픽). 소유자=상품(공유) XOR 옵션값(색상별)
CREATE TABLE product_schema.product_images
(
    id              uuid         NOT NULL DEFAULT gen_random_uuid(),
    product_id      uuid,                       -- ref: products.id. 기본(공유) 이미지 소유
    option_value_id uuid,                       -- ref: product_option_values.id (주로 색상). 옵션값 종속 이미지
    image_role      varchar(10)  NOT NULL,      -- ENUM: GALLERY(대표 ≤5), DETAIL(상세 ≤10), BODY(본문 인라인), SWATCH(색칩)
    image_key       varchar(500) NOT NULL,
    sort_order      smallint     NOT NULL DEFAULT 0,
    created_at      timestamptz  NOT NULL,
    CONSTRAINT pk_product_images PRIMARY KEY (id),
    CONSTRAINT ck_product_images_owner CHECK ((product_id IS NULL) <> (option_value_id IS NULL)),
    CONSTRAINT ck_product_images_swatch CHECK (image_role <> 'SWATCH' OR option_value_id IS NOT NULL),
    CONSTRAINT ck_product_images_body CHECK (image_role <> 'BODY' OR product_id IS NOT NULL)
);
CREATE INDEX ON product_schema.product_images (product_id, image_role, sort_order);
CREATE INDEX ON product_schema.product_images (option_value_id, image_role, sort_order);
-- 옵션값당 색칩 1개
CREATE UNIQUE INDEX ON product_schema.product_images (option_value_id) WHERE image_role = 'SWATCH';

COMMENT ON TABLE product_schema.product_images IS '상품·옵션 이미지 통합(폴리모픽). 소유자=상품(공유) XOR 옵션값(색상별). 색상 선택 시 GALLERY·DETAIL은 해당 옵션값 이미지로 오버라이드(없으면 상품 공유 폴백), BODY는 항상 상품 공유, SWATCH는 색칩. 개수 상한(대표 5/상세 10)은 앱 강제';
COMMENT ON COLUMN product_schema.product_images.product_id IS 'ref: products.id. 기본(공유) 이미지 소유. option_value_id와 정확히 하나만 NOT NULL';
COMMENT ON COLUMN product_schema.product_images.option_value_id IS 'ref: product_option_values.id (주로 색상). 옵션값 종속 이미지 — 선택 시 기본 오버라이드';
COMMENT ON COLUMN product_schema.product_images.image_role IS 'ENUM: GALLERY(대표 ≤5), DETAIL(상세 ≤10), BODY(본문 인라인), SWATCH(색칩)';
COMMENT ON COLUMN product_schema.product_images.image_key IS '스토리지 키';
COMMENT ON COLUMN product_schema.product_images.sort_order IS 'GALLERY/DETAIL 노출 순서. BODY는 본문 HTML 내 위치가 순서이므로 0. SWATCH는 값당 1개';

-- ============================================================
-- §5  상품 옵션
-- ============================================================

-- 상품별 옵션 타입 (색상, 사이즈 등). 계층 순서로 드롭박스 선택 흐름 결정
CREATE TABLE product_schema.product_option_types
(
    id                 uuid        NOT NULL DEFAULT gen_random_uuid(),
    product_id         uuid        NOT NULL, -- ref: products.id
    attribute_group_id uuid,                 -- ref: option_attribute_groups.id (NULL=완전 커스텀)
    name               varchar(50) NOT NULL, -- 그룹 선택 시 복사, 커스텀 시 직접 입력
    sort_order         smallint    NOT NULL, -- 옵션 선택 계층 순서 (1=최상위)
    deleted_at         timestamptz,          -- 논리 삭제 일시
