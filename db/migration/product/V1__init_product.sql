-- ============================================================
-- §31  Outbox 이벤트 (PG ↔ ES 비동기 동기화)
-- ============================================================

-- Transactional Outbox. 비즈니스 INSERT와 같은 트랜잭션에서 INSERT → 워커가 폴링하여 ES 반영
CREATE TABLE product_schema.outbox_events
(
    id             bigint      NOT NULL, -- 앱 생성 TSID (시간순 단조 증가, auto increment 미사용)
    aggregate_type varchar(50) NOT NULL, -- ENUM: product, combination, order, review
    aggregate_id   uuid        NOT NULL, -- 도메인 객체 ID. FK 미설정 — 삭제 후에도 발행 가능
    event_type     varchar(50) NOT NULL, -- ENUM: UPSERTED, DELETED, STOCK_CHANGED, PRICE_CHANGED, DISCOUNT_WINNER_CHANGED, REVIEW_ADDED, OPTION_VALUE_RENAMED
    payload        jsonb       NOT NULL, -- 이벤트 페이로드
    created_at     timestamptz NOT NULL DEFAULT now(),
    processed_at   timestamptz,          -- 워커 처리 완료 일시. NULL=미처리. 완료 7일 후 삭제
    retry_count    integer     NOT NULL DEFAULT 0, -- 재시도 횟수. 3 이상이면 Dead Letter
    last_error     text,                 -- 마지막 실패 사유. 성공 시 NULL
    CONSTRAINT pk_product_outbox_events PRIMARY KEY (id),
    CONSTRAINT ck_outbox_retry_count CHECK (retry_count >= 0)
);
CREATE INDEX ON product_schema.outbox_events (created_at) WHERE processed_at IS NULL;       -- 워커 폴링 큐
CREATE INDEX ON product_schema.outbox_events (aggregate_type, aggregate_id);
CREATE INDEX ON product_schema.outbox_events (event_type, created_at);
CREATE INDEX ON product_schema.outbox_events (retry_count, created_at) WHERE retry_count > 0; -- 재시도 우선순위

COMMENT ON TABLE product_schema.outbox_events IS 'Transactional Outbox — PG ↔ ES 비동기 동기화 원자성 보장. 비즈니스 INSERT와 같은 트랜잭션에서 INSERT → 별도 워커가 폴링하여 ES 반영';
COMMENT ON COLUMN product_schema.outbox_events.id IS 'PK — 앱 생성 TSID(시간순 단조 증가, auto increment 미사용)';
COMMENT ON COLUMN product_schema.outbox_events.aggregate_type IS 'ENUM: product, combination, order, review';
COMMENT ON COLUMN product_schema.outbox_events.aggregate_id IS '도메인 객체 ID. FK 미설정 — 삭제 후에도 발행 가능';
COMMENT ON COLUMN product_schema.outbox_events.event_type IS 'ENUM: UPSERTED, DELETED, STOCK_CHANGED, PRICE_CHANGED, DISCOUNT_WINNER_CHANGED, REVIEW_ADDED, OPTION_VALUE_RENAMED';
COMMENT ON COLUMN product_schema.outbox_events.payload IS '이벤트 페이로드. ES 인덱싱에 필요한 데이터 포함';
COMMENT ON COLUMN product_schema.outbox_events.processed_at IS '워커 처리 완료 일시. NULL=미처리. 완료 7일 후 삭제';
COMMENT ON COLUMN product_schema.outbox_events.retry_count IS '재시도 횟수. 3 이상이면 Dead Letter';
COMMENT ON COLUMN product_schema.outbox_events.last_error IS '마지막 실패 사유. 성공 시 NULL';
