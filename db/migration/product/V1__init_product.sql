COMMENT ON TABLE product_schema.category_option_attribute_groups IS '카테고리별 권장 속성 그룹 매핑. 판매자 옵션 등록 화면 드롭박스 소스';
COMMENT ON COLUMN product_schema.category_option_attribute_groups.category_id IS 'ref: categories.id';
COMMENT ON COLUMN product_schema.category_option_attribute_groups.attribute_group_id IS 'ref: option_attribute_groups.id';
COMMENT ON COLUMN product_schema.category_option_attribute_groups.sort_order IS '드롭박스 노출 순서';

-- ============================================================
-- §4  상품
