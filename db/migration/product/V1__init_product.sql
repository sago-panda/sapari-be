CREATE INDEX ON product_schema.product_option_types (product_id, sort_order);
CREATE INDEX ON product_schema.product_option_types (attribute_group_id);
-- 옵션 타입명 중복 방지
CREATE UNIQUE INDEX ON product_schema.product_option_types (product_id, name) WHERE deleted_at IS NULL;

COMMENT ON TABLE product_schema.product_option_types IS '상품별 옵션 타입 (색상, 사이즈 등). 계층 순서로 드롭박스 선택 흐름 결정';
COMMENT ON COLUMN product_schema.product_option_types.product_id IS 'ref: products.id';
COMMENT ON COLUMN product_schema.product_option_types.attribute_group_id IS 'ref: option_attribute_groups.id (NULL=완전 커스텀)';
