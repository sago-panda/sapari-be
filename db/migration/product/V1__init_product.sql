-- product 도메인 초기 스키마 (카탈로그·옵션·가격·문의·랭킹/검색·outbox/audit — review는 review_schema로 분리)
-- 출처: erd-dbdiagram.io-final-add-live.md (§2 카테고리 · §3 옵션 속성 템플릿 · §4 상품 · §5 상품 옵션
--       · §6 기간 할인 + 승자 캐시 · §13 상품 Q&A · §19 운영(베스트/감사) · §20 검색 로그 · §31 Outbox)
-- 규칙:
--   * 물리 FK 미사용 (도메인 간/내부 모두). 참조는 uuid/bigint id 컬럼으로만 표현.
--   * bigint PK: categories는 IDENTITY(DB 자동생성, LongTimeEntity 매핑); 검색로그·통계·outbox는
--     앱 생성 TSID(serial 미사용, 배치 COPY 호환) — INSERT 시 앱이 id 주입.
--   * uuid PK는 앱 생성 UUIDv7 권장, gen_random_uuid()는 fallback 기본값.
--   * 검색 로그/통계는 비파티션 단순 테이블 (월별 RANGE 파티셔닝은 운영 단계에서 적용).
CREATE SCHEMA IF NOT EXISTS product_schema;

-- categories.path 용 ltree 확장 (DB당 1회. flyway_role에 권한 없으면 DBA가 사전 생성)
CREATE EXTENSION IF NOT EXISTS ltree;

-- ============================================================
-- §2  카테고리 (ltree)
-- ============================================================

-- 상품 카테고리 트리 (ltree, depth 최대 4). id는 ltree 라벨로 직접 사용 → bigint
CREATE TABLE product_schema.categories
(
    id         bigint       GENERATED BY DEFAULT AS IDENTITY, -- DB 자동생성. ltree 라벨로 직접 사용
    parent_id  bigint,                -- self ref (NULL=최상위)
    path       ltree        NOT NULL, -- 라벨=id 숫자 그대로 (예: 1042.3851.7720)
    name       varchar(100) NOT NULL,
    depth      smallint     NOT NULL, -- 깊이 (1~4), nlevel(path) 캐시
    sort_order integer      NOT NULL DEFAULT 0,
    is_active  boolean      NOT NULL DEFAULT true,
    created_at timestamptz  NOT NULL,
    updated_at timestamptz  NOT NULL,
    CONSTRAINT pk_categories PRIMARY KEY (id)
);
CREATE INDEX ON product_schema.categories USING GIST (path);
CREATE INDEX ON product_schema.categories (parent_id, sort_order);
CREATE INDEX ON product_schema.categories (depth, is_active, sort_order);

COMMENT ON TABLE product_schema.categories IS '상품 카테고리 트리 (ltree, depth 최대 4)';
COMMENT ON COLUMN product_schema.categories.id IS 'PK — bigint IDENTITY(DB 자동생성). ltree 라벨로 직접 사용';
COMMENT ON COLUMN product_schema.categories.parent_id IS '상위 카테고리 id (NULL=최상위)';
COMMENT ON COLUMN product_schema.categories.path IS 'ltree 경로. 라벨=id 숫자 그대로. GiST 인덱스로 서브트리/조상 조회';
COMMENT ON COLUMN product_schema.categories.name IS '카테고리명';
COMMENT ON COLUMN product_schema.categories.depth IS '깊이 (1~4), nlevel(path) 캐시';
COMMENT ON COLUMN product_schema.categories.sort_order IS '동일 부모 내 노출 순서';
COMMENT ON COLUMN product_schema.categories.is_active IS '노출 여부';

-- ============================================================
-- §3  옵션 속성 템플릿
-- ============================================================

-- 옵션 속성 그룹 템플릿. 관리자 공용 + 판매자 커스텀 구분
