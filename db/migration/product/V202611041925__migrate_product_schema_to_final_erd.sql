-- product 스키마를 seed DDL(V1, 설계 sapari_postgres.sql 기반)에서 최종 ERD(erd-dbdiagram.io-final-add-live.md)로 옮긴다.
-- 이미 적용된 V1은 수정하지 않는다(Flyway checksum) — 차이는 전부 이 전진 마이그레이션이 담는다.
--
-- 바뀌는 것:
--   * 카테고리 id: uuid → bigint IDENTITY (ltree 라벨로 id를 그대로 쓴다). 참조 컬럼(products, category_option_attribute_groups)도 bigint
--   * 이미지 통합: product_images가 소유자(상품 XOR 옵션값)·역할(GALLERY/DETAIL/BODY/SWATCH)을 갖고,
--     product_detail_images · product_option_value_images · product_option_combination_images를 흡수한다
--   * 옵션 룰: product_option_dependency · product_option_incompatibility → product_option_configs(jsonb 룰, 상품 1:1)
--   * 재고 예약: product_option_combinations.reserved_stock + stock_reservations 원장. products.stock_total 제거
--   * 낙관적 락 version 컬럼 (products, product_option_combinations)
--   * 앱 생성 TSID id: product_search_logs · search_keyword_daily_stats · outbox_events의 bigserial 시퀀스 제거
--   * 할인 정책 priority, 부분 인덱스·CHECK·자연키 유니크 보강, 테이블·컬럼 COMMENT
--
-- 데이터 변환이 불가능한 변경(uuid → bigint, 테이블 흡수·삭제, 컬럼 삭제)이 있으므로, 영향받는 테이블에 행이 있으면
-- 아무것도 바꾸지 않고 실패한다. 이 마이그레이션 시점에 product 스키마를 쓰는 배포 환경은 없다.

DO $$
DECLARE
    t text;
    has_rows boolean;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'categories', 'category_option_attribute_groups', 'products', 'product_images',
        'product_detail_images', 'product_option_value_images', 'product_option_combination_images',
        'product_option_dependency', 'product_option_incompatibility']
    LOOP
        EXECUTE format('SELECT EXISTS (SELECT 1 FROM product_schema.%I)', t) INTO has_rows;
        IF has_rows THEN
            RAISE EXCEPTION 'product_schema.% 에 데이터가 있어 스키마 전환을 중단합니다 — 데이터 이관 마이그레이션이 먼저 필요합니다', t;
        END IF;
    END LOOP;
END
$$;

-- ============================================================
-- 카테고리 id: uuid → bigint IDENTITY
-- ============================================================
-- 빈 테이블만 통과하므로(위 가드) USING NULL로 타입만 바꾼다. 컬럼 인덱스·PK는 타입 변경 시 같은 이름으로 재생성된다.
ALTER TABLE product_schema.categories
    ALTER COLUMN id DROP DEFAULT,
    ALTER COLUMN id TYPE bigint USING NULL,
    ALTER COLUMN parent_id TYPE bigint USING NULL;
ALTER TABLE product_schema.categories
    ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE product_schema.category_option_attribute_groups
    ALTER COLUMN category_id TYPE bigint USING NULL;

ALTER TABLE product_schema.products
    ALTER COLUMN category_id TYPE bigint USING NULL;

-- ============================================================
-- 상품: 재고 합계 캐시 제거, 낙관적 락 version, 인덱싱 stale 부분 인덱스
-- ============================================================
ALTER TABLE product_schema.products
    DROP COLUMN stock_total,
    ADD COLUMN version bigint NOT NULL DEFAULT 0;

DROP INDEX product_schema.products_search_indexed_at_idx;
CREATE INDEX ON product_schema.products (search_indexed_at)
    WHERE search_indexed_at IS NULL OR search_indexed_at < updated_at;        -- stale 후보

