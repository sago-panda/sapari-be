DROP TABLE product_schema.product_option_incompatibility;

-- 상품별 옵션 저작 룰(조합 추가금 + 불가 조합) 통합 보관
CREATE TABLE product_schema.product_option_configs
(
    product_id      uuid        NOT NULL, -- PK이자 ref: products.id (1:1)
    surcharge_rules jsonb,                -- 조합 추가금 룰 [{"valueIds":["uuid",...],"amount":50000}]
    exclusion_rules jsonb,                -- 불가 조합 룰 [{"valueIds":["uuid",...],"reason":"..."}]
    created_at      timestamptz NOT NULL,
    updated_at      timestamptz NOT NULL,
    CONSTRAINT pk_product_option_configs PRIMARY KEY (product_id)
);

-- 주문 이전 단계(체크아웃·라이브 플래시) 재고 선예약 원장
CREATE TABLE product_schema.stock_reservations
(
    id             uuid        NOT NULL DEFAULT gen_random_uuid(),
    combination_id uuid        NOT NULL, -- ref: product_option_combinations.id
    reserved_by    uuid,                 -- ref: users.id. 예약 주체. 비회원은 NULL + session_id
    session_id     varchar(100),         -- 비회원 홀드 트래킹
    order_item_id  uuid,                 -- ref: order_items.id. 주문 전환 시 연결. 주문前 홀드는 NULL
    quantity       integer     NOT NULL, -- 예약 수량
    status         varchar(15) NOT NULL DEFAULT 'HELD', -- ENUM: HELD, COMMITTED, RELEASED, EXPIRED
    expires_at     timestamptz NOT NULL, -- 홀드 만료 일시. 배치/Redis TTL 회수
    created_at     timestamptz NOT NULL,
    updated_at     timestamptz NOT NULL,
    CONSTRAINT pk_stock_reservations PRIMARY KEY (id)
);
CREATE INDEX ON product_schema.stock_reservations (combination_id, status);
CREATE INDEX ON product_schema.stock_reservations (expires_at) WHERE status = 'HELD'; -- 만료 회수 배치
CREATE INDEX ON product_schema.stock_reservations (reserved_by, status);
CREATE INDEX ON product_schema.stock_reservations (order_item_id);

