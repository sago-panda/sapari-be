-- 이미지 통합 (폴리모픽 product_images)
-- ============================================================
DROP TABLE product_schema.product_detail_images;
DROP TABLE product_schema.product_option_value_images;
DROP TABLE product_schema.product_option_combination_images;

ALTER TABLE product_schema.product_images
    ALTER COLUMN product_id DROP NOT NULL,
    ADD COLUMN option_value_id uuid,
    ADD COLUMN image_role varchar(10) NOT NULL,
    ALTER COLUMN sort_order SET DEFAULT 0,
    ADD CONSTRAINT ck_product_images_owner CHECK ((product_id IS NULL) <> (option_value_id IS NULL)),
    ADD CONSTRAINT ck_product_images_swatch CHECK (image_role <> 'SWATCH' OR option_value_id IS NOT NULL),
    ADD CONSTRAINT ck_product_images_body CHECK (image_role <> 'BODY' OR product_id IS NOT NULL);

DROP INDEX product_schema.product_images_product_id_sort_order_idx;
CREATE INDEX ON product_schema.product_images (product_id, image_role, sort_order);
CREATE INDEX ON product_schema.product_images (option_value_id, image_role, sort_order);
-- 옵션값당 색칩 1개
CREATE UNIQUE INDEX ON product_schema.product_images (option_value_id) WHERE image_role = 'SWATCH';

